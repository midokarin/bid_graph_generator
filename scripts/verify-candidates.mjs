// Browser acceptance uses local synthetic data only. It never calls an external model.
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE??'playwright');
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const url=process.env.BIAOSHU_WEB_URL??'http://127.0.0.1:5192';
const out='docs/evidence/candidates';await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const visible=()=>page.locator('.task-workbench:not([hidden])');
const button=name=>visible().getByRole('button',{name,exact:true});
const waitFor=async predicate=>{const until=Date.now()+15000;while(!await predicate()){assert.ok(Date.now()<until,'condition timed out');await new Promise(resolve=>setTimeout(resolve,25))}};
const screenshot=async name=>{if(await button('关闭提示').count())await button('关闭提示').click();for(const width of [1440,1920]){await page.setViewportSize({width,height:width===1440?900:1080});await page.screenshot({path:`${out}/${name}-${width}.png`,fullPage:false})}};
await page.addInitScript(()=>{
 window.__saved=[];
 window.showSaveFilePicker=async()=>({createWritable:async()=>({write:async content=>window.__saved.push(JSON.parse(content)),close:async()=>{}})});
});
try{
 const health=await (await page.request.get(`${url}/api/v1/health`)).json();assert.equal(health.provider,'stub','requires a dedicated stub backend');
 await page.goto(url);await page.getByText('替身模型 · 本机服务',{exact:true}).waitFor();
 await screenshot('initial');
 assert.equal(await visible().getByRole('switch',{name:'多方案生成'}).isChecked(),false);
 const requests=[];page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/generations'))requests.push(r.postDataJSON())});
 await visible().getByRole('switch',{name:'多方案生成'}).check();
 await button('生成 3 个方案').click();
 await visible().getByText('3 / 3 已完成',{exact:true}).waitFor({timeout:30000});
 await waitFor(()=>visible().locator('.candidate-card .button').first().isEnabled());
 assert.deepEqual(requests.map(r=>r.flow_variant),['mainline','branches','stages']);
 assert.equal(new Set(requests.map(r=>r.source_text)).size,1);
 assert.equal(await visible().locator('.candidate-card.success').count(),3);
 assert.equal(await visible().locator('.candidate-card .sub-badge').filter({hasText:'布局推荐'}).count(),1);
 assert.equal(await button('保存项目').isEnabled(),false);
 await button('版本记录').click();assert.equal(await visible().locator('.version-card').count(),0);await button('关闭弹窗').click();
 await screenshot('choices');
 await button('放大方案 2').click();await visible().locator('dialog[open] svg[role=img]').waitFor();
 await screenshot('enlarged');await page.keyboard.press('Escape');
 await visible().locator('.candidate-card').nth(1).getByRole('button',{name:'采用此方案',exact:true}).click();
 await visible().locator('.paper').waitFor();
 await button('保存项目').click();await waitFor(async()=>await page.evaluate(()=>window.__saved.length)===1);
 const saved=await page.evaluate(()=>window.__saved[0]);assert.equal(saved.versions.length,1);assert.equal(saved.current_revision,1);
 assert.equal(await visible().locator('.task-item-title i').count(),0,'saved adopted candidate should clear task dirty indicator');
 assert.equal(saved.versions[0].layout.nodes.length,saved.versions[0].spec.nodes.length);
 assert.equal('candidates' in saved,false);
 await button('比较本次方案').click();
 assert.equal(await visible().locator('.candidate-card').nth(1).getByRole('button',{name:'已采用'}).isEnabled(),false);
 await visible().locator('.candidate-card').nth(0).getByRole('button',{name:'采用此方案',exact:true}).click();
 await button('保存项目').click();await waitFor(async()=>await page.evaluate(()=>window.__saved.length)===2);
 const savedAgain=await page.evaluate(()=>window.__saved[1]);assert.equal(savedAgain.versions.length,2);assert.deepEqual(savedAgain.versions[0],saved.versions[0]);
 await button('下一步：导出').click();
 const downloadPromise=page.waitForEvent('download');await button('下载 SVG').click();const download=await downloadPromise;
 const exported=await readFile(await download.path(),'utf8');assert.ok(exported.includes('<svg'));assert.ok(exported.includes(savedAgain.versions[1].spec.title));
 const pngPromise=page.waitForEvent('download');await visible().locator('dialog').getByRole('button',{name:'下载草稿 PNG',exact:true}).click();const pngDownload=await pngPromise;
 const png=await readFile(await pngDownload.path());assert.deepEqual([...png.subarray(0,8)],[137,80,78,71,13,10,26,10]);assert.ok(png.readUInt32BE(16)>0&&png.readUInt32BE(20)>0);
 await button('关闭弹窗').click();await screenshot('adopted');
 await button('比较本次方案').click();
 await button('新建任务').click();assert.equal(await visible().locator('.candidate-card').count(),0);
 await button('切换任务：任务 1').click();assert.equal(await visible().locator('.candidate-card').count(),3);
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal overflow');
 await page.screenshot({path:`${out}/mobile-390.png`,fullPage:true});
 await visible().getByRole('textbox',{name:'业务内容 *',exact:true}).fill('新的内容');assert.equal(await visible().locator('.candidate-card').count(),0);
 await button('甘特图').click();assert.equal(await visible().getByRole('switch',{name:'多方案生成'}).count(),0);
 await button('载入示例').click();await button('生成图表草稿').click();await visible().locator('.paper').waitFor({timeout:30000});
 assert.equal(requests.at(-1).diagram_type,'gantt');assert.equal(requests.at(-1).flow_variant,undefined);
 assert.deepEqual(errors,[]);
 await writeFile(`${out}/browser-result.json`,JSON.stringify({provider:'local stub backend; no external model calls',checks:['three controlled prompt variants','real API, SSE, ELK worker and validation','no version before adoption','enlarged candidate preview','chosen layout saved with one version','second adoption preserves prior version','PNG and SVG export','task isolation and candidates survive switching','source changes invalidate candidates','Gantt remains single generation','1440x900, 1920x1080 and 390px mobile','no browser exceptions'],errors},null,2)+'\n');
 console.log('Local API candidate browser checks passed.');
}finally{await browser.close()}
